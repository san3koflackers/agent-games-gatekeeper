// Generate src/wasm-b64.js + src/zkey-b64.js from the circuit artifacts.
// The Worker cannot read files at runtime, so the wasm + zkey are embedded
// as base64 strings (total ~2.7 MB — well under the 10 MB Worker limit).
// Run: node tools/build-assets.mjs
// (Re-run only if the circuit artifacts change; they are platform-published
// and versioned by vkHash, so they should not change mid-season.)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const circuits = path.resolve(root, "..", "circuits");

function emit(srcFile, outFile, exportName) {
  const buf = fs.readFileSync(path.join(circuits, srcFile));
  const b64 = buf.toString("base64");
  const js =
    `// AUTO-GENERATED by tools/build-assets.mjs — do not edit by hand.\n` +
    `// Source: ../circuits/${srcFile} (${buf.length} bytes, base64 ${b64.length} chars).\n` +
    `export const ${exportName} = "${b64}";\n`;
  fs.writeFileSync(path.join(root, "src", outFile), js);
  console.log(`${outFile}: ${buf.length} bytes -> ${b64.length} base64 chars`);
}

emit("gatekeeper.wasm", "wasm-b64.js", "WASM_B64");
emit("gatekeeper_final.zkey", "zkey-b64.js", "ZKEY_B64");

// Verification key (exported with snarkjs; used for local proof verification
// before responding). Source: ../docs/probe/vk.json.
const vk = JSON.parse(fs.readFileSync(path.join(root, "..", "docs", "probe", "vk.json"), "utf8"));
fs.writeFileSync(
  path.join(root, "src", "vk.js"),
  `// AUTO-GENERATED by tools/build-assets.mjs — do not edit by hand.\n// Source: ../docs/probe/vk.json (exported from gatekeeper_final.zkey).\n// Registered vkHash on zkVerify mainnet: 0x6b79c6012a6d8651f3e13bc4d2a20370280ab49700c90c5316d4168bfbad77b0\nexport const VK = ${JSON.stringify(vk)};\n`,
);
console.log("vk.js: verification key embedded");
console.log("done.");
